//! CLI command reference generator from clap definitions.

use clap::{Arg, Command, CommandFactory};
use tomet_ast::{Block, Document, Element, ElementValue, Placement, Section, Sigil, Value};
use tomet_config::PrinterConfig;
use tomet_tree::{ElementExt, element_new};

use crate::cli::Cli;
use crate::commands::spec::util::{code, code_block, dummy, inlines, list, paragraph, paragraphs, text};

const DOC_ID: &str = "doc-cliDocRf";
const NOTICE: &str = "Generated by `tomet spec cli` from the clap definitions in \
     `apps/cli/src/cli.rs`. Do not edit it: change the doc comments there and run \
     the command again.";

/// Renders the complete formatted CLI specification .tmt string.
pub fn render(config: &PrinterConfig) -> String {
    let mut root = Cli::command();
    root.build();
    let doc = document(&mut root);
    let printed = tomet_printer::document_to_tm_with_config(&doc, config);
    tomet_formatter::format_source_with_config(&printed, config)
}

pub fn document(root: &mut Command) -> Document {
    let mut meta = element_new(Sigil::named("meta")).with_placement(Placement::Block);
    meta.value = Some(ElementValue::from_map(Value::Map(vec![(
        "id".to_string(),
        Value::String(DOC_ID.to_string()),
    )])));

    let mut blocks = vec![Block::Element(meta)];
    push_command(root, 1, &mut blocks);
    // Insert notice after the title section block and its main description
    blocks.insert(2, paragraph(inlines(NOTICE)));

    Document::new(blocks, dummy())
}

fn push_command(cmd: &mut Command, level: usize, out: &mut Vec<Block>) {
    let name = cmd
        .get_bin_name()
        .map_or_else(|| cmd.get_name().to_string(), str::to_string);
    out.push(Block::Section(Section::new(
        level,
        vec![text(&name)],
        dummy(),
    )));

    let about = cmd
        .get_long_about()
        .or_else(|| cmd.get_about())
        .map(|s| s.to_string())
        .unwrap_or_default();
    for para in paragraphs(&about) {
        out.push(paragraph(inlines(&para)));
    }

    let usage = cmd.render_usage().to_string();
    let usage = usage.trim().strip_prefix("Usage:").unwrap_or(&usage).trim();
    out.push(Block::Element(code_block(usage)));

    let positional: Vec<&Arg> = cmd
        .get_arguments()
        .filter(|a| listed(a) && a.is_positional())
        .collect();
    let options: Vec<&Arg> = cmd
        .get_arguments()
        .filter(|a| listed(a) && !a.is_positional())
        .collect();
    if !positional.is_empty() {
        out.push(paragraph(vec![text("Arguments:")]));
        out.push(Block::List(list(positional.iter().map(|a| item(cmd, a)))));
    }
    if !options.is_empty() {
        out.push(paragraph(vec![text("Options:")]));
        out.push(Block::List(list(options.iter().map(|a| item(cmd, a)))));
    }

    let subs: Vec<String> = cmd
        .get_subcommands()
        .filter(|s| s.get_name() != "help" && !s.is_hide_set())
        .map(|s| s.get_name().to_string())
        .collect();
    for sub in subs {
        if let Some(sub) = cmd.find_subcommand_mut(&sub) {
            push_command(sub, level + 1, out);
        }
    }
}

fn listed(arg: &Arg) -> bool {
    !arg.is_hide_set() && !matches!(arg.get_id().as_str(), "help" | "version")
}

fn item(cmd: &Command, arg: &Arg) -> Element {
    let mut content = vec![code(&label(arg))];

    let help = arg
        .get_long_help()
        .or_else(|| arg.get_help())
        .map(|s| s.to_string())
        .unwrap_or_default();
    let help = help.split_whitespace().collect::<Vec<_>>().join(" ");
    let mentions_default = help.to_lowercase().contains("default");
    if !help.is_empty() {
        let end = if help.ends_with(['.', '!', '?']) {
            ""
        } else {
            "."
        };
        content.extend(inlines(&format!(": {help}{end}")));
    }

    let defaults: Vec<String> = arg
        .get_default_values()
        .iter()
        .map(|v| v.to_string_lossy().into_owned())
        .collect();
    if arg.get_action().takes_values() && !defaults.is_empty() && !mentions_default {
        content.push(text(" Default: "));
        content.push(code(&defaults.join(", ")));
        content.push(text("."));
    }

    let mut conflicts: Vec<String> = cmd
        .get_arg_conflicts_with(arg)
        .into_iter()
        .filter(|c| listed(c))
        .map(label_short)
        .collect();
    conflicts.sort();
    if !conflicts.is_empty() {
        content.push(text(" Conflicts with "));
        for (i, c) in conflicts.iter().enumerate() {
            if i > 0 {
                content.push(text(", "));
            }
            content.push(code(c));
        }
        content.push(text("."));
    }

    let mut el = element_new(Sigil::Bare).with_placement(Placement::Block);
    el.content = Some(vec![paragraph(content)]);
    el
}

fn label(arg: &Arg) -> String {
    let value = arg
        .get_value_names()
        .and_then(|names| names.first().map(|n| n.to_string()))
        .unwrap_or_else(|| arg.get_id().as_str().to_uppercase());
    if arg.is_positional() {
        let many = arg.get_num_args().is_some_and(|r| r.max_values() > 1);
        let dots = if many { "..." } else { "" };
        return if arg.is_required_set() {
            format!("<{value}>{dots}")
        } else {
            format!("[{value}]{dots}")
        };
    }
    let mut names = Vec::new();
    if let Some(short) = arg.get_short() {
        names.push(format!("-{short}"));
    }
    if let Some(long) = arg.get_long() {
        names.push(format!("--{long}"));
    }
    let mut out = names.join(", ");
    if arg.get_action().takes_values() {
        out.push_str(&format!(" <{value}>"));
    }
    out
}

fn label_short(arg: &Arg) -> String {
    match (arg.get_long(), arg.get_short()) {
        (Some(long), _) => format!("--{long}"),
        (None, Some(short)) => format!("-{short}"),
        _ => label(arg),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;
    use tomet_ast::Entry;
    use crate::commands::spec::util::guard_triggers;
    use crate::commands::spec::{SpecTarget, spec_cmd};

    fn rendered() -> String {
        render(&PrinterConfig::default())
    }

    #[test]
    fn every_subcommand_and_its_options_are_in_the_reference() {
        let text = rendered();
        let mut root = Cli::command();
        root.build();
        for sub in root.get_subcommands().filter(|s| s.get_name() != "help") {
            assert!(
                text.contains(&format!("tomet {}", sub.get_name())),
                "missing section for `{}`",
                sub.get_name()
            );
        }
        assert!(text.contains("--force"), "options are listed");
    }

    #[test]
    fn the_output_is_valid_tmt_and_already_formatted() {
        let text = rendered();
        tomet_parser::parse_document(&text).expect("the generated reference parses");
        assert_eq!(
            tomet_formatter::format_source_with_config(&text, &PrinterConfig::default()),
            text,
            "`tomet format --check` must accept the generated file"
        );
    }

    #[test]
    fn reading_the_output_back_keeps_every_paragraph_and_section() {
        fn count(blocks: &[Block], sections: &mut usize, paragraphs: &mut usize) {
            for block in blocks {
                match block {
                    Block::Section(s) => {
                        *sections += 1;
                        count(&s.blocks, sections, paragraphs);
                    }
                    Block::Paragraph(_) => *paragraphs += 1,
                    Block::Element(_) => {}
                    Block::List(_) => {}
                }
            }
        }
        let mut root = Cli::command();
        root.build();
        let (mut want_s, mut want_p) = (0, 0);
        count(&document(&mut root).blocks, &mut want_s, &mut want_p);

        let parsed = tomet_parser::parse_document(&rendered()).unwrap();
        let (mut got_s, mut got_p) = (0, 0);
        count(&parsed.blocks, &mut got_s, &mut got_p);
        assert_eq!((got_s, got_p), (want_s, want_p));
    }

    #[test]
    fn the_output_is_deterministic() {
        assert_eq!(rendered(), rendered());
    }

    #[test]
    fn check_reports_a_missing_stale_and_current_file() {
        let dir = std::env::temp_dir().join(format!("tomet_test_cli_spec_{}", nanoid::nanoid!()));
        let out = dir.join("generated").join("cli.tmt");

        assert!(
            spec_cmd(Some(SpecTarget::Cli), false, Some(&out), true).is_err(),
            "missing"
        );

        spec_cmd(Some(SpecTarget::Cli), false, Some(&out), false).unwrap();
        assert!(
            spec_cmd(Some(SpecTarget::Cli), false, Some(&out), true).is_ok(),
            "current"
        );

        fs::write(&out, "stale\n").unwrap();
        assert!(
            spec_cmd(Some(SpecTarget::Cli), false, Some(&out), true).is_err(),
            "stale"
        );

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn text_that_looks_like_an_element_stays_text_when_read_back() {
        fn stray(inlines: &[tomet_ast::Inline], found: &mut Vec<String>) {
            for inline in inlines {
                if let tomet_ast::Inline::Element(el) = inline
                    && !el.sigil.is_bare_named("raw")
                {
                    found.push(format!("{:?}", el.sigil));
                }
            }
        }
        fn walk(blocks: &[Block], found: &mut Vec<String>) {
            for block in blocks {
                match block {
                    Block::Paragraph(p) => stray(&p.content, found),
                    Block::Section(s) => walk(&s.blocks, found),
                    Block::Element(el) => {
                        walk(el.content.as_deref().unwrap_or(&[]), found);
                        if let Some(tomet_ast::ElementValue::Group(entries)) = &el.value {
                            for entry in entries {
                                if let Entry::Element(item) = entry {
                                    walk(item.content.as_deref().unwrap_or(&[]), found);
                                }
                            }
                        }
                    }
                    Block::List(list) => walk_list(list, found),
                }
            }
        }
        fn walk_list(list: &tomet_ast::List, found: &mut Vec<String>) {
            for item in &list.items {
                walk(item.element.content.as_deref().unwrap_or(&[]), found);
                if let Some(sub) = &item.sublist {
                    walk_list(sub, found);
                }
            }
        }
        let parsed = tomet_parser::parse_document(&rendered()).unwrap();
        let mut found = Vec::new();
        walk(&parsed.blocks, &mut found);
        assert!(found.is_empty(), "text came back as elements: {found:?}");

        assert_eq!(guard_triggers("Overrides @config.").len(), 3);
        assert_eq!(
            guard_triggers("cost $5 or a@ b").len(),
            1,
            "not element-like"
        );
    }

    #[test]
    fn backticks_become_inline_code_and_an_odd_one_stays_text() {
        assert_eq!(inlines("a `b` c").len(), 3);
        assert_eq!(inlines("it`s").len(), 1);
    }
}
