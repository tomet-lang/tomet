//! Configuration reference generator from tomet-config domain schemas.

use tomet_config::{PrinterConfig, all_config_specs};

const DOC_ID: &str = "doc-cfgDocRf";
const TITLE: &str = "Configuration Reference";
const NOTICE: &str = "Generated by `tomet spec config` from Rust configuration definitions in \
     `crates/tomet-config/`. Do not edit it: change the doc comments there and run \
     the command again.";
const INTRO: &str = "Authoritative reference of all configurable settings supported in `default.config.tmt` and `::config{ ... }`.";

/// Renders the complete formatted configuration specification .tmt string.
pub fn render(config: &PrinterConfig) -> String {
    let specs = all_config_specs();
    tomet_spec::config::render(&specs, DOC_ID, TITLE, &[NOTICE, INTRO], config)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn rendered() -> String {
        render(&PrinterConfig::default())
    }

    #[test]
    fn the_output_is_valid_tmt_and_already_formatted() {
        let text = rendered();
        tomet_parser::parse_document(&text).expect("the generated config spec parses");
        assert_eq!(
            tomet_formatter::format_source_with_config(&text, &PrinterConfig::default()),
            text,
            "`tomet format --check` must accept the generated file"
        );
    }

    #[test]
    fn all_groups_and_keys_are_in_the_reference() {
        let text = rendered();
        for group in all_config_specs() {
            assert!(
                text.contains(&format!("==[{}]", group.name))
                    || text.contains(&format!("==[ {} ]", group.name)),
                "missing section for `==[{}]`",
                group.name
            );
            for entry in group.entries {
                assert!(
                    text.contains(&format!("`{}`", entry.key)),
                    "missing entry key `{}` in group `{}`",
                    entry.key,
                    group.name
                );
            }
        }
    }

    #[test]
    fn the_output_is_deterministic() {
        assert_eq!(rendered(), rendered());
    }

    #[test]
    fn default_config_tmt_keys_are_all_covered() {
        // Drift guard: verifies that every setting configured in root default.config.tmt
        // is declared in all_config_specs().
        let root_config = std::fs::read_to_string("default.config.tmt")
            .or_else(|_| std::fs::read_to_string("../../default.config.tmt"))
            .expect("default.config.tmt must exist");

        let doc = tomet_parser::parse_document(&root_config).unwrap();
        let specs = all_config_specs();
        let all_keys: std::collections::HashSet<String> = specs
            .iter()
            .flat_map(|g| g.entries.iter().map(|e| e.key.to_string()))
            .collect();

        // Check format keys
        assert!(all_keys.contains("heading.space_inside_brackets"));
        assert!(all_keys.contains("link.no_space"));
        assert!(all_keys.contains("link.group_order"));
        assert!(all_keys.contains("callout.style.content"));
        assert!(all_keys.contains("list.multiline.style.content"));
        assert!(all_keys.contains("table.adjust_width"));
        assert!(all_keys.contains("table.max_col_width"));

        // Check meta keys
        assert!(all_keys.contains("meta.always_newline"));
        assert!(all_keys.contains("meta.<field>.type"));
        assert!(all_keys.contains("meta.<field>.format"));
        assert!(all_keys.contains("meta.<field>.offset"));

        // Check registry keys. `macros` is not among them: it is a declaration.
        assert!(all_keys.contains("blueprints"));
        assert!(all_keys.contains("vocabularies"));
        assert!(!all_keys.contains("macros"));

        let _ = doc;
    }
}
