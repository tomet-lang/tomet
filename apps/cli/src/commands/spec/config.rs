//! Configuration reference generator from tomet-config domain schemas.

use tomet_ast::{Block, Document, Element, ElementValue, Placement, Section, Sigil, Value};
use tomet_config::{ConfigEntrySpec, ConfigGroupSpec, PrinterConfig, all_config_specs};
use tomet_tree::{ElementExt, element_new};

use crate::commands::spec::util::{code, dummy, inlines, list, paragraph, paragraphs, text};

const DOC_ID: &str = "doc-cfgDocRf";
const NOTICE: &str = "Generated by `tomet spec config` from Rust configuration definitions in \
     `crates/tomet-config/`. Do not edit it: change the doc comments there and run \
     the command again.";

/// Renders the complete formatted configuration specification .tmt string.
pub fn render(config: &PrinterConfig) -> String {
    let specs = all_config_specs();
    let doc = document(&specs);
    let printed = tomet_printer::document_to_tm_with_config(&doc, config);
    tomet_formatter::format_source_with_config(&printed, config)
}

pub fn document(groups: &[ConfigGroupSpec]) -> Document {
    let mut meta = element_new(Sigil::named("meta")).with_placement(Placement::Block);
    meta.value = Some(ElementValue::from_map(Value::Map(vec![(
        "id".to_string(),
        Value::String(DOC_ID.to_string()),
    )])));

    let mut blocks = vec![
        Block::Element(meta),
        Block::Section(Section::new(
            1,
            vec![text("Configuration Reference")],
            dummy(),
        )),
        paragraph(inlines(NOTICE)),
        paragraph(inlines(
            "Authoritative reference of all configurable settings supported in `default.config.tmt` and `@config{ ... }`.",
        )),
    ];

    for group in groups {
        push_group(group, &mut blocks);
    }

    Document::new(blocks, dummy())
}

fn push_group(group: &ConfigGroupSpec, out: &mut Vec<Block>) {
    out.push(Block::Section(Section::new(
        2,
        vec![text(group.name)],
        dummy(),
    )));

    if !group.description.is_empty() {
        for para in paragraphs(group.description) {
            out.push(paragraph(inlines(&para)));
        }
    }

    if !group.entries.is_empty() {
        out.push(Block::List(list(group.entries.iter().map(entry_item))));
    }
}

fn entry_item(entry: &ConfigEntrySpec) -> Element {
    let mut content = vec![code(entry.key)];

    let mut type_info = format!(" ({})", entry.value_type);
    if let Some(default) = entry.default_value {
        type_info = format!(" ({}, default: `{default}`)", entry.value_type);
    }
    content.extend(inlines(&type_info));

    if !entry.description.is_empty() {
        let desc = entry.description.trim();
        let end = if desc.ends_with(['.', '!', '?']) {
            ""
        } else {
            "."
        };
        content.extend(inlines(&format!(": {desc}{end}")));
    }

    if !entry.aliases.is_empty() {
        content.push(text(" Aliases: "));
        for (i, alias) in entry.aliases.iter().enumerate() {
            if i > 0 {
                content.push(text(", "));
            }
            content.push(code(alias));
        }
        content.push(text("."));
    }

    let mut el = element_new(Sigil::Bare).with_placement(Placement::Block);
    el.content = Some(vec![paragraph(content)]);
    el
}

#[cfg(test)]
mod tests {
    use super::*;

    fn rendered() -> String {
        render(&PrinterConfig::default())
    }

    #[test]
    fn the_output_is_valid_tmt_and_already_formatted() {
        let text = rendered();
        tomet_parser::parse_document(&text).expect("the generated config spec parses");
        assert_eq!(
            tomet_formatter::format_source_with_config(&text, &PrinterConfig::default()),
            text,
            "`tomet format --check` must accept the generated file"
        );
    }

    #[test]
    fn all_groups_and_keys_are_in_the_reference() {
        let text = rendered();
        for group in all_config_specs() {
            assert!(
                text.contains(&format!("==[{}]", group.name))
                    || text.contains(&format!("==[ {} ]", group.name)),
                "missing section for `==[{}]`",
                group.name
            );
            for entry in group.entries {
                assert!(
                    text.contains(&format!("`{}`", entry.key)),
                    "missing entry key `{}` in group `{}`",
                    entry.key,
                    group.name
                );
            }
        }
    }

    #[test]
    fn the_output_is_deterministic() {
        assert_eq!(rendered(), rendered());
    }

    #[test]
    fn default_config_tmt_keys_are_all_covered() {
        // Drift guard: verifies that every setting configured in root default.config.tmt
        // is declared in all_config_specs().
        let root_config = std::fs::read_to_string("default.config.tmt")
            .or_else(|_| std::fs::read_to_string("../../default.config.tmt"))
            .expect("default.config.tmt must exist");

        let doc = tomet_parser::parse_document(&root_config).unwrap();
        let specs = all_config_specs();
        let all_keys: std::collections::HashSet<String> = specs
            .iter()
            .flat_map(|g| g.entries.iter().map(|e| e.key.to_string()))
            .collect();

        // Check format keys
        assert!(all_keys.contains("heading.space_inside_brackets"));
        assert!(all_keys.contains("link.no_space"));
        assert!(all_keys.contains("link.group_order"));
        assert!(all_keys.contains("callout.style.content"));
        assert!(all_keys.contains("list.multiline.style.content"));
        assert!(all_keys.contains("table.adjust_width"));
        assert!(all_keys.contains("table.max_col_width"));

        // Check meta keys
        assert!(all_keys.contains("meta.always_newline"));
        assert!(all_keys.contains("meta.<field>.type"));
        assert!(all_keys.contains("meta.<field>.format"));
        assert!(all_keys.contains("meta.<field>.offset"));

        // Check registry and macros keys
        assert!(all_keys.contains("blueprints"));
        assert!(all_keys.contains("vocabularies"));
        assert!(all_keys.contains("macros"));

        let _ = doc;
    }
}

